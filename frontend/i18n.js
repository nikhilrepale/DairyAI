  function walk(root, language) {
    root.querySelectorAll?.(".field").forEach((field, index) => {
      const label = field.querySelector("label");
      const control = field.querySelector("input, select, textarea");
      if (!label || !control) return;
      if (!control.id) control.id = `dairyai-field-${index}-${Math.random().toString(36).slice(2, 7)}`;
      if (!label.htmlFor) label.htmlFor = control.id;
    });
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (!node.parentElement || /^(SCRIPT|STYLE)$/.test(node.parentElement.tagName) || node.parentElement.closest(".language-toggle")) continue;
      if (node.__i18nOriginal === undefined) node.__i18nOriginal = node.nodeValue;
      const translated = translateText(node.__i18nOriginal, language);
      if (node.nodeValue !== translated) node.nodeValue = translated;
    }
    root.querySelectorAll?.("[placeholder], [title], [aria-label]").forEach(element => {
      for (const attr of ["placeholder", "title", "aria-label"]) {
        if (!element.hasAttribute(attr)) continue;
        const key = `__i18n_${attr}`;
        if (element[key] === undefined) element[key] = element.getAttribute(attr);
        const translated = translateText(element[key], language);
        if (element.getAttribute(attr) !== translated) element.setAttribute(attr, translated);
      }
    });
    root.querySelectorAll?.("th:not([scope])").forEach(header => header.setAttribute("scope", "col"));
    root.querySelectorAll?.("table").forEach(table => {
      const headings = [...table.querySelectorAll("thead th")].map(header =>
        header.__i18nOriginal || header.textContent.trim()
      );
      table.querySelectorAll("tbody tr").forEach(row => {
        [...row.cells].forEach((cell, index) => {
          cell.querySelectorAll("input, select, textarea").forEach(control => {
            if (control.__i18nTableField === undefined) {
              control.__i18nTableField = headings[index] || "Table field";
            }
            control.setAttribute("aria-label", translateText(control.__i18nTableField, language));
          });
        });
      });
    });
    root.querySelectorAll?.(".tablewrap").forEach(region => {
      if (!region.hasAttribute("tabindex")) region.setAttribute("tabindex", "0");
      if (!region.hasAttribute("role")) region.setAttribute("role", "region");
      const source = region.__i18nTableLabel || "Use horizontal scrolling to view all columns";
      region.__i18nTableLabel = source;
      region.setAttribute("aria-label", translateText(source, language));
    });
  }

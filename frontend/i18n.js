  const observer = new MutationObserver(records => {
    for (const record of records) {
      if (record.type === "childList") record.addedNodes.forEach(node => {
        if (node.nodeType === Node.ELEMENT_NODE) walk(node, language);
        else if (node.nodeType === Node.TEXT_NODE && !node.parentElement?.closest(".language-toggle")) {
          if (node.__i18nOriginal === undefined) node.__i18nOriginal = node.nodeValue;
          node.nodeValue = translateText(node.__i18nOriginal, language);
        }
      });
      else if (record.type === "characterData") {
        const node = record.target;
        if (node.parentElement?.closest(".language-toggle")) continue;
        if (node.__i18nOriginal === undefined) node.__i18nOriginal = node.nodeValue;
        const translated = translateText(node.__i18nOriginal, language);
        if (node.nodeValue !== translated) node.nodeValue = translated;
      }
    }
  });
  observer.observe(document.body, {subtree: true, childList: true, characterData: true});
